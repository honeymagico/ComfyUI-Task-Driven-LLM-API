/* Stand-in for ComfyUI's scripts/api.js.

Responses come from mock-data.js, which is generated by the real Python
modules -- so the shapes are the real ones, not invented ones. */
import { MOCK } from "./mock-data.js";

const json = (body) => ({
  ok: true,
  status: 200,
  async json() {
    return body;
  },
  async blob() {
    return new Blob([JSON.stringify(body)], { type: "application/json" });
  },
});

export const api = {
  __calls: [],
  async fetchApi(path, options = {}) {
    api.__calls.push({ path, options });
    const method = (options.method || "GET").toUpperCase();
    const empty = new URLSearchParams(location.search).get("mode") === "empty";
    if (path.endsWith("/library") && method === "GET") {
      if (!empty) return json(MOCK.library);
      return json({ ...MOCK.library, library: { ...MOCK.library.library, tasks: [] }, labels: [], warnings: [] });
    }
    if (path.endsWith("/library") && method === "POST") return json({ ok: true, warnings: [], labels: MOCK.library.labels });
    if (path.endsWith("/config") && method === "GET") return json(MOCK.config);
    if (path.endsWith("/config") && method === "POST") return json(MOCK.config);
    if (path.endsWith("/preview")) return json(MOCK.preview_default);
    if (path.endsWith("/models")) return json(MOCK.models);
    if (path.endsWith("/probe")) return json(MOCK.probe);
    if (path.endsWith("/open_folder")) return json({ ok: true, path: MOCK.library.locate.prompts_dir });
    if (path.endsWith("/export")) return json(MOCK.library.library);
    return json({ ok: false, error: `harness has no mock for ${method} ${path}` });
  },
  addEventListener() {},
};
